export function calculateFlightTotalUsd(
  flight: FlightSchedule,
  cabin: CabinClass,
  passengers: number,
): {unitPriceUsd: number; totalPriceUsd: number} {
  const safePassengers = Math.min(6, Math.max(1, Math.round(passengers)));
  const unitPriceUsd =
    cabin === 'business'
      ? Math.round(flight.economyPriceUsd * flight.businessMultiplier)
      : flight.economyPriceUsd;
  return {
    unitPriceUsd,
    totalPriceUsd: unitPriceUsd * safePassengers,
  };
}
